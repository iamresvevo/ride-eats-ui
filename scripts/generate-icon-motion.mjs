import { coreMotion, coreAliases } from "../react/icons/core-motion.js";
import fs from "node:fs";
import { authoredMotion } from "../react/icons/authored-motion.js";
import { loaders } from "../react/icons/loaders.js";
import { motionFamily, shapeMotion } from "../react/icons/motion-profiles.js";
const icons = [];
for (const loader of Object.values(loaders))
  for (const [name, nodes] of Object.entries((await loader()).default)) {
    const geometry = nodes.some(
      ([tag, attributes], index) =>
        shapeMotion(name, tag, attributes, index, nodes).attributeName !==
        "stroke-opacity",
    );
    icons.push({
      name,
      family: motionFamily(name),
      treatment:
        ["headset", "folder"].includes(name) || authoredMotion[name]
          ? "authored geometry"
          : geometry
            ? "static — pending choreography"
            : "static — pending choreography",
    });
  }
for (const name of [...Object.keys(coreMotion), ...Object.keys(coreAliases)]) {
  const item = icons.find((icon) => icon.name === name);
  if (item) item.treatment = "authored geometry";
  else icons.push({ name, family: "explicit", treatment: "authored geometry" });
}
icons.sort((a, b) => a.name.localeCompare(b.name));
const counts = {};
for (const icon of icons)
  counts[icon.treatment] = (counts[icon.treatment] || 0) + 1;
fs.writeFileSync(
  "react/icons/motion-names.js",
  "// Generated by scripts/generate-icon-motion.mjs.\nexport const geometryMotionNames = " +
    JSON.stringify(
      icons
        .filter((icon) => icon.treatment === "authored geometry")
        .map((icon) => icon.name),
    ) +
    ";\n",
);
fs.writeFileSync(
  "docs/icon-motion-coverage.json",
  JSON.stringify(
    {
      note: "Programmatic treatment inventory, not a claim of individual visual review or original glyph artwork.",
      counts,
      icons,
    },
    null,
    2,
  ) + "\n",
);
